                                        <div class="col-md-12" id="info-compdec">
                                        	<h4>Informações sobre Comunidades</h4>
                                        	<ul>
                                        		<li>"Comunidade atendida" -  refere-se ao nome do bairro, distrito, povoado, vila etc.</li>
                                                
                                                <li>"População atendida" - Neste campo, informar a quantidade (número de pessoas) que serão atendidas. Somente deverão ser consideradas 
                                                aquelas pessoas que necessitam de abastecimento emergencial (Não lançar quantidade de famílias). Pessoas que residem em moradias que
                                                 dispõe de poços artesianos ou qualquer sistema de fornecimento de água não deverão ser consideradas para atendimento emergencial.
                                                
                                                <li>“Trecho”: os campos deverão ser preenchidos com a distância em quilômetros a ser percorrido em cada tipo de pavimentação para o
                                                 acesso à comunidade atendida. Deverá ser considerada apenas a distância do ponto de captação até a comunidade. O retorno deverá ser
                                                  desconsiderado. Quanto à característica da via, considera-se pavimentada a via asfaltada, com calçamento ou similares.</li>
                                                
                                                <li>“Distância total”: somatório do trecho a ser percorrido até a comunidade, (pavimentado e não pavimentado). Deverá ser considerada
                                                 apenas a distância do ponto de captação até a comunidade, o retorno deverá ser desconsiderado. </li>
                                                
                                                <li>“Coordenada Geográfica da comunidade”: referenciamento da comunidade com a coordenada geográfica do ponto mais distante a ser
                                                 atendido na comunidade no formato GRAUS DECIMAIS, com 06(seis) casa após a vírgula, ex. "-12.123456".</li> 
                                                
                                                <li>“Ponto de captação” - Informar o órgão responsável pelo local de abastecimento do caminhão pipa e o nome da empresa concessionária
                                                 Copasa, Copanor, SAAE, preferencialmente situada no município. Caso seja informada a captação em poço artesiano, manancial ou barragem,
                                                  deverá descrever o nome do local e junto ao PMDA, anexar um laudo que ateste a boa qualidade da água para consumo humano (em
                                                   conformidade com a PORTARIA Nº 2.914, DE 12 DE DEZEMBRO DE 2011, do Ministério da Saúde), sendo de responsabilidade do município
                                                    a garantia da qualidade da água. O exame da qualidade da água deverá obrigatoriamente ocorrer mensalmente e o laudo ser enviado
                                                     a CEDEC/MG SOB PENA DE SUSPENÇÃO DO ATENDIMENTO.
                                                Caso a captação seja indicada em um município vizinho, deverá ser anexado ao PMDA, declaração da empresa concessionária, na qual
                                                 deverá constar a permissão do abastecimento dos caminhões pipa que atenderão o município durante a vigência da operação. (SERÁ 
                                                 INVALIDADO PMDA QUE NÃO CONSTAR A REFERIDA DECLARAÇÃO).
                                                O “laudo de potabilidade” da água e a “declaração da empresa concessionária” deverão ser anexados no PMDA Eletrônio através do PORTAL
                                                DE SERVIÇOS. 
                                                 “Coordenada Geográfica do Ponto de Captação”: referenciamento através de coordenada geográfica de cada ponto de captação no 
                                                 formato GRAUS DECIMAIS, com 06(seis) casa após a vírgula, ex. "-12.123456".</li> 
                                        	</ul>
                                        
